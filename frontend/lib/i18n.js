const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState('en');

  useEffect(() => {
    if (typeof window === 'undefined') return;
    const saved = localStorage.getItem('nanny_language');
    if (saved && LANGUAGES.includes(saved)) setLanguage(saved);
  }, []);

  useEffect(() => {
    if (typeof window === 'undefined') return;
    localStorage.setItem('nanny_language', language);
  }, [language]);

  const value = useMemo(() => ({
    language,
    setLanguage,
    t(scope, key, fallback = '') {
      return translations[language]?.[scope]?.[key] ?? fallback ?? key;
    },
    translateTitle(title) {
      return translations[language]?.shell?.titleMap?.[title] || title;
    },
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error('useLanguage must be used inside LanguageProvider');
  return ctx;
}

export const availableLanguages = LANGUAGES;
